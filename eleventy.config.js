/* ============================================================
   挂载框架 · Eleventy 配置
   ------------------------------------------------------------
   用法：把带 front matter 的 HTML 丢进 pages/，提交时
   githooks/pre-commit 自动构建，页面被挂载到全站：
     · 输出到站点根目录（URL: /<文件名>/）
     · 注入站点外壳（导航/页脚/主题/SEO，见 _includes/layout.njk）
     · 生成 mounted.js  → 首页归档/领域计数/最近更新/筛选自动收录
     · 生成 sitemap.xml → 收录全部页面
   ============================================================ */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

/* data.js 是浏览器脚本：注入 window 后加载，拿到领域/类型注册表 */
global.window = global.window || {};
require('./data.js');
const ZP = global.window.ZP;
const FIELD_IDS = new Set((ZP.fields || []).map(f => f.id));
const TYPE_IDS = new Set(['w', 'p', 't', 'c']);
const DATE_RE = /^\d{4}\.(0[1-9]|1[0-2])$/;
const GENERATED_MARK = 'GENERATED by Eleventy';

/* 本轮挂载收集，eleventy.after 用它生成 mounted.js / sitemap.xml */
let mountedPages = [];

function parseFrontMatter(src) {
  const m = src.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) return { data: {}, body: src };
  const data = {};
  m[1].split(/\r?\n/).forEach(line => {
    const i = line.indexOf(':');
    if (i > 0) data[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  });
  return { data, body: src.slice(m[0].length) };
}

/* 资源指纹：给 style.css/app.js/data.js/mounted.js 的引用加 ?v=<内容哈希>。
   GitHub Pages 对静态资源发 max-age=600，没有指纹时「新 HTML + 旧缓存 CSS/JS」
   会让用户在部署后10分钟内看到错乱渲染（内容哈希让 URL 必变 → 必回源）。 */
function stampAssets() {
  const assets = ['style.css', 'app.js', 'data.js', 'mounted.js'];
  const hashes = {};
  assets.forEach(a => {
    hashes[a] = crypto.createHash('sha256')
      .update(fs.readFileSync(path.join(__dirname, a))).digest('hex').slice(0, 8);
  });
  const worksDir = path.join(__dirname, 'works');
  const targets = ['index.html', 'pages/_includes/layout.njk',
    ...(fs.existsSync(worksDir)
      ? fs.readdirSync(worksDir).filter(f => f.endsWith('.html')).map(f => 'works/' + f)
      : [])];
  targets.forEach(t => {
    const fp = path.join(__dirname, t);
    if (!fs.existsSync(fp)) return;
    let s = fs.readFileSync(fp, 'utf8');
    const orig = s;
    assets.forEach(a => {
      const esc = a.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      s = s.replace(
        new RegExp('(href|src)="((?:\\.\\./|\\/)?' + esc + ')(\\?v=[0-9a-f]*)?"', 'g'),
        (m, attr, ref) => `${attr}="${ref}?v=${hashes[a]}"`
      );
    });
    if (s !== orig) fs.writeFileSync(fp, s);
  });
}

module.exports = function (eleventyConfig) {
  /* 所有挂载页统一套用站点外壳 */
  eleventyConfig.addGlobalData('layout', 'layout.njk');

  /* ── 构建前：扫描 pages/，校验并收集（出错即中止构建 → 拦截提交） ── */
  eleventyConfig.on('eleventy.before', () => {
    mountedPages = [];
    const dir = path.join(__dirname, 'pages');
    if (!fs.existsSync(dir)) return;

    for (const name of fs.readdirSync(dir).sort()) {
      if (!name.endsWith('.html') || name.startsWith('_')) continue;
      const src = fs.readFileSync(path.join(dir, name), 'utf8');
      const { data, body } = parseFrontMatter(src);
      const slug = name.replace(/\.html$/, '');
      const errors = [];

      if (!data.title) errors.push('缺少 title（归档标题）');
      if (!data.desc) errors.push('缺少 desc（一句说明，会显示在归档与分享卡片）');
      if (!data.field) errors.push('缺少 field（领域 id）');
      else if (!FIELD_IDS.has(data.field))
        errors.push(`field "${data.field}" 不存在于 data.js，可用：${[...FIELD_IDS].join(', ')}`);
      if (!data.type) errors.push('缺少 type');
      else if (!TYPE_IDS.has(data.type)) errors.push(`type 必须是 w/p/t/c（当前 "${data.type}"）`);
      if (!data.published) errors.push('缺少 published（YYYY.MM；不能叫 date，那是 Eleventy 保留键）');
      else if (!DATE_RE.test(data.published)) errors.push(`published 格式应为 YYYY.MM（当前 "${data.published}"）`);

      if (/<html[\s>]/i.test(body) || /<body[\s>]/i.test(body))
        errors.push('这是完整 HTML 文档（含 <html>/<body>）；挂载页只写正文片段，页面外壳由框架注入');

      /* 输出目录防覆盖：已存在且不是本框架生成的 → 拒绝 */
      const target = path.join(__dirname, slug);
      if (fs.existsSync(target)) {
        const idx = path.join(target, 'index.html');
        const ours = fs.existsSync(idx) && fs.readFileSync(idx, 'utf8').includes(GENERATED_MARK);
        if (!ours) errors.push(`输出目录 ./${slug}/ 已存在且非挂载框架生成，拒绝覆盖`);
      }

      if (errors.length)
        throw new Error(`pages/${name} 挂载失败：\n  - ` + errors.join('\n  - '));

      mountedPages.push({
        f: data.field, type: data.type, date: data.published,
        t: data.title, s: data.desc, u: `/${slug}/`
      });
    }
    /* 与归档同序：按日期倒序 */
    mountedPages.sort((a, b) => (b.date || '').localeCompare(a.date || ''));
  });

  /* ── 构建后：生成首页数据与站点地图 ── */
  eleventyConfig.on('eleventy.after', () => {
    fs.writeFileSync(
      path.join(__dirname, 'mounted.js'),
      '/* GENERATED by Eleventy — 由 pages/*.html 的 front matter 生成，勿手改 */\n' +
      'window.ZP_MOUNT = ' + JSON.stringify({ pages: mountedPages }, null, 2) + ';\n'
    );

    const statics = ['/', '/code.html'];
    const worksDir = path.join(__dirname, 'works');
    const works = fs.existsSync(worksDir)
      ? fs.readdirSync(worksDir).filter(f => f.endsWith('.html')).map(f => '/works/' + f)
      : [];
    const urls = [...statics, ...works, ...mountedPages.map(p => p.u)];
    const today = new Date().toISOString().slice(0, 10);
    const xml =
      '<?xml version="1.0" encoding="UTF-8"?>\n' +
      '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
      urls.map(u =>
        '  <url>\n' +
        `    <loc>https://zerophix.github.io${u}</loc>\n` +
        `    <lastmod>${today}</lastmod>\n` +
        '  </url>'
      ).join('\n') +
      '\n</urlset>\n';
    fs.writeFileSync(path.join(__dirname, 'sitemap.xml'), xml);

    stampAssets();
  });

  return {
    dir: { input: 'pages', output: '.', includes: '_includes' },
    /* 关键：HTML 不做模板渲染 —— front matter 照常剥离，正文原样输出 */
    htmlTemplateEngine: false,
    templateFormats: ['html']
  };
};
